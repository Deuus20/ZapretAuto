"""Generate CODEMAP.md: every module with its classes and functions, so a reader can pick what to open.

Usage: python tools/codemap.py (tests/test_core.py checks the file is current).
"""
import ast
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Code map\nGenerated by `python tools/codemap.py`; do not edit. Find a definition with grep `def <name>`.\n"
def _names(body) -> list[str]:
    return [n.name for n in body if isinstance(n, ast.FunctionDef | ast.AsyncFunctionDef)]
def _module(path: Path) -> str:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    doc = (ast.get_docstring(tree) or "").split("\n")[0]
    out = [f"\n## {path.relative_to(ROOT).as_posix()}" + (f": {doc}" if doc else "")]
    if funcs := _names(tree.body):
        out.append("- " + ", ".join(funcs))
    out += [f"- **{c.name}**: " + ", ".join(_names(c.body)) for c in tree.body if isinstance(c, ast.ClassDef)]
    return "\n".join(out) + "\n"
def build() -> str:
    files = [ROOT / "main.py", *sorted(p for d in ("app", "scripts", "tools") for p in (ROOT / d).rglob("*.py"))]
    return HEADER + "".join(_module(p) for p in files if p.stat().st_size)
if __name__ == "__main__":
    (ROOT / "CODEMAP.md").write_text(build(), encoding="utf-8", newline="\n")
